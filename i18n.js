export function getSavedLanguage() {
  return localStorage.getItem("site_lang") || "en";
}

export function getProjectDescription(project, lang = getSavedLanguage()) {
  return lang === "id" && project.description_id ? project.description_id : project.description;
}

export function getProjectRole(project, lang = getSavedLanguage()) {
  return lang === "id" && project.role_id ? project.role_id : project.role;
}

export function getProjectDate(project, lang = getSavedLanguage()) {
  return lang === "id" && project.date_id ? project.date_id : project.date;
}

export function setLanguage(lang) {
  if (lang !== "en" && lang !== "id") lang = "en";
  localStorage.setItem("site_lang", lang);
  document.documentElement.setAttribute("lang", lang);
  applyTranslations(lang);
  updateLangButtons(lang);
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

export function toggleLanguage() {
  const current = getSavedLanguage();
  const next = current === "en" ? "id" : "en";
  setLanguage(next);
  return next;
}

function getNestedTranslation(obj, keyPath) {
  return keyPath.split(".").reduce((prev, curr) => (prev ? prev[curr] : null), obj);
}

export function applyTranslations(lang) {
  const dict = translations[lang] || translations.en;

  // 1. Text elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const text = getNestedTranslation(dict, key);
    if (text !== null && text !== undefined) {
      el.textContent = text;
    }
  });

  // 2. HTML elements with data-i18n-html attribute
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    const html = getNestedTranslation(dict, key);
    if (html !== null && html !== undefined) {
      el.innerHTML = html;
    }
  });

  // 3. Section names in dynamic island
  document.querySelectorAll(".island-link").forEach((link) => {
    const secKey = link.getAttribute("data-sec-key");
    if (secKey && dict.nav[secKey]) {
      link.textContent = dict.nav[secKey];
      link.setAttribute("data-name", dict.island[secKey.toUpperCase()] || dict.nav[secKey]);
    }
  });

  // 4. Update island current active section label if present
  const islandSecName = document.getElementById("island-sec-name");
  const activeLink = document.querySelector(".island-link.active");
  if (islandSecName && activeLink) {
    const secKey = activeLink.getAttribute("data-sec-key");
    const name = (secKey && dict.island[secKey.toUpperCase()]) || activeLink.getAttribute("data-name");
    if (name) islandSecName.textContent = name;
  }

  // 5. Instantly reposition active pill to match new text width & layout
  requestAnimationFrame(() => {
    repositionActivePill();
  });
  setTimeout(() => {
    repositionActivePill();
  }, 50);
  setTimeout(() => {
    repositionActivePill();
  }, 150);
}

export function repositionActivePill() {
  const activePill = document.getElementById("nav-active-pill");
  const activeLink = document.querySelector(".island-link.active");
  if (!activePill || !activeLink) return;
  const parent = activeLink.parentElement;
  if (!parent) return;

  const parentRect = parent.getBoundingClientRect();
  const linkRect = activeLink.getBoundingClientRect();
  if (linkRect.width === 0 || parentRect.width === 0) return;

  activePill.style.left = `${linkRect.left - parentRect.left}px`;
  activePill.style.width = `${linkRect.width}px`;
  activePill.style.opacity = "1";
}

function updateLangButtons(lang) {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const enSpan = btn.querySelector(".lang-en");
    const idSpan = btn.querySelector(".lang-id");
    if (enSpan && idSpan) {
      if (lang === "id") {
        enSpan.classList.remove("active");
        idSpan.classList.add("active");
      } else {
        enSpan.classList.add("active");
        idSpan.classList.remove("active");
      }
    }
  });

  document.querySelectorAll(".mobile-lang-btn").forEach((btn) => {
    const targetLang = btn.getAttribute("data-set-lang");
    if (targetLang === lang) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });
}

export function initI18n() {
  const currentLang = getSavedLanguage();
  document.documentElement.setAttribute("lang", currentLang);

  // Bind toggle buttons and individual segmented pill clicks
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const enSpan = btn.querySelector(".lang-en");
    const idSpan = btn.querySelector(".lang-id");

    if (enSpan) {
      enSpan.addEventListener("click", (e) => {
        e.stopPropagation();
        setLanguage("en");
      });
    }

    if (idSpan) {
      idSpan.addEventListener("click", (e) => {
        e.stopPropagation();
        setLanguage("id");
      });
    }

    btn.addEventListener("click", (e) => {
      e.preventDefault();
      toggleLanguage();
    });
  });

  // Bind mobile specific buttons if any
  document.querySelectorAll(".mobile-lang-btn").forEach((btn) => {
    btn.addEventListener("click", (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute("data-set-lang");
      if (targetLang) setLanguage(targetLang);
    });
  });

  // Apply initially
  applyTranslations(currentLang);
  updateLangButtons(currentLang);
}
